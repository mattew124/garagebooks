#!/usr/bin/env bash
# =============================================================================
# dev.sh — run the dev stack on its own test database.
#
#   scripts/dev.sh setup             first run in a new checkout: venv + local files check; run it again
#                                    after merging main to install any requirements that changed
#   scripts/dev.sh info              this checkout's stack: name, URL path, ports
#   scripts/dev.sh up [--image REF]  start; first run creates and seeds the test DB.
#                                    --image runs a released image instead of
#                                    building this working tree (test a candidate)
#   scripts/dev.sh refresh           re-copy TeslaMate data, keeping test expenses
#   scripts/dev.sh reset             wipe the test DB, test expenses included
#   scripts/dev.sh down              stop, keeping the test DB
#   scripts/dev.sh sample-expenses [clear]
#                                    add made-up expenses to the test DB to try the app with
#                                    (re-run to refresh them; `clear` removes only those)
#   scripts/dev.sh sample-invoices   write made-up invoice PDFs into the stack's invoice folder
#                                    (.dev/invoices/Sample invoices), to try the import with
#   scripts/dev.sh demo <command>    a second stack of invented data, for screenshots. Same commands
#                                    as above (up, reset, down, destroy, psql, logs, info), plus
#                                    `demo screenshots`. TeslaMate's tables come from a fresh
#                                    schema-only dump of the live database each time it is built;
#                                    the rows are generated by scripts/demo-seed.sql, not copied.
#   scripts/dev.sh destroy           remove this checkout's stack, test DB, image and .dev folder
#   scripts/dev.sh list              every dev stack on this machine
#   STAND_IN=1 scripts/dev.sh ...    use the stand-in claims connector even when dev.env names a real one
#   scripts/dev.sh prune [--dry-run] destroy every dev stack whose branch has merged into main, or whose
#                                    checkout is gone (any checkout's stacks, not only this one's)
#   scripts/dev.sh auto-prune [on|off]
#                                    run `prune` hourly from cron (the main checkout's copy), or stop it;
#                                    with neither, says whether it is on
#   scripts/dev.sh test-browser [--onedrive]
#                                    run the browser tests against the dev stack;
#                                    --onedrive fails if the real OneDrive checks can't run
#   scripts/dev.sh onedrive-save     keep this stack's OneDrive sign-in in a file outside
#                                    the repository (ONEDRIVE_DEV_FILE)
#   scripts/dev.sh onedrive-link     load that sign-in into this stack, pointed at the
#                                    /Expenses test folder
#   scripts/dev.sh psql [args]       psql on the test database
#   scripts/dev.sh logs              follow the app's logs (and the worker's, with SCHEDULER=worker)
#
# Settings come from ./dev.env (gitignored; see dev.env.example). That includes where the stack's invoice
# folder is: .dev/invoices here, a folder of its own on a mounted share (DEV_INVOICES_SHARE) or one folder
# of your choosing (DEV_INVOICES_DIR).
#
# Each git worktree gets its own stack, test DB and URL path
# (/garagebooks-dev/<worktree>/), so parallel sessions can't replace each other's
# running code. The main checkout keeps /garagebooks-dev/. DEV_INSTANCE overrides
# the name.
#
# The seed only READS TeslaMate (pg_dump, COPY TO STDOUT). It copies the full
# cars and charging_processes tables and one positions row per hour, with
# latitude, longitude and elevation blanked, so no location history reaches the
# test database. Throwaway passwords live in .dev/env (gitignored, 0600).
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if [ -f dev.env ]; then
    set -a
    # shellcheck disable=SC1091
    . ./dev.env
    set +a
fi
# STAND_IN=1 uses the stand-in claims connector whatever dev.env says. The browser tests need it: they submit claims.
if [ "${STAND_IN:-}" = 1 ]; then unset DEV_CLAIMS_CONNECTOR_URL DEV_CLAIMS_CONNECTOR_KEY_FILE; fi
# The private key the app signs claims requests with: your own for a real connector, else the stand-in's.
export DEV_CLAIMS_KEY_SOURCE="${DEV_CLAIMS_CONNECTOR_KEY_FILE:-./.dev/claims/stand-in.key}"
export APP_TZ="${APP_TZ:-UTC}"
SEED_FROM="${SEED_FROM:-teslamate-database-1}"
ENVF=.dev/env

# `demo <command>` runs the command on a second stack, with generated data (see header).
DEMO=0
if [ "${1:-}" = demo ]; then DEMO=1; shift; fi
SHOTS=.dev/screenshots; [ "$DEMO" = 0 ] || SHOTS=.dev/demo-screenshots
INVOICES=.dev/invoices; [ "$DEMO" = 0 ] || INVOICES=.dev/demo-invoices
DEV_UID="$(id -u)"; DEV_GID="$(id -g)"

# ---- which dev stack this checkout owns ----------------------------------------

instance_name() {
    if [ -n "${DEV_INSTANCE:-}" ]; then
        printf '%s' "$DEV_INSTANCE"
    elif [ "$(git rev-parse --git-dir 2>/dev/null)" != "$(git rev-parse --git-common-dir 2>/dev/null)" ]; then
        basename "$ROOT"   # a linked worktree: named after its folder
    fi
}

INSTANCE="$(instance_name | tr 'A-Z_' 'a-z-' | tr -c 'a-z0-9-' '-' | sed 's/^-*//; s/-*$//' | cut -c1-30)"
if [ "$DEMO" = 1 ]; then
    # Shorter, so the suffix survives the length limit and the demo has its own name.
    INSTANCE="$(printf '%s' "$INSTANCE" | cut -c1-24 | sed 's/-*$//')"
    INSTANCE="${INSTANCE:+$INSTANCE-}demo"
fi
if [ -n "$(instance_name)" ] && [ "$DEMO" = 0 ] && { [ -z "$INSTANCE" ] || [ "$INSTANCE" = grafana ]; }; then
    echo "dev: can't derive a usable stack name from '$(instance_name)'; set DEV_INSTANCE" >&2
    exit 2
fi
# The stack's invoice folder (INVOICES_DIR): mounted into the app, which runs as you so that what it
# writes there is yours. Put PDFs in it by hand to try the import. In order of preference:
#   DEV_INVOICES_DIR    (dev.env) exactly this folder, e.g. one on a mounted NAS share
#   DEV_INVOICES_SHARE  (dev.env) a mounted share: each stack gets its own folder in it, named after the
#                       stack, so branches never mix their test PDFs
#   otherwise           .dev/invoices in this checkout
# The demo stack always uses its own folder: its screenshots are published.
INVOICES_SHARE=""
if [ "$DEMO" = 0 ] && [ -n "${DEV_INVOICES_DIR:-}" ]; then
    :
elif [ "$DEMO" = 0 ] && [ -n "${DEV_INVOICES_SHARE:-}" ]; then
    INVOICES_SHARE="${DEV_INVOICES_SHARE%/}"
    DEV_INVOICES_DIR="$INVOICES_SHARE/${INSTANCE:-main}"
else
    DEV_INVOICES_DIR="$ROOT/$INVOICES"
fi
export DEV_UID DEV_GID DEV_INVOICES_DIR
# Shown on the app's Invoice storage page. The demo's screenshots are published, so it shows an
# example path instead of this checkout's.
export DEV_INVOICES_SHOWN="$DEV_INVOICES_DIR"
[ "$DEMO" = 0 ] || export DEV_INVOICES_SHOWN=/mnt/nas/cars/invoices

if [ -z "$INSTANCE" ]; then
    PROJECT=garagebooks-dev
    export DEV_BASE_PATH=/garagebooks-dev DEV_ROUTER_SUFFIX= DEV_TAG=dev
    export DEV_UI_PRIORITY=110 DEV_GRAFANA_PRIORITY=120
    export DEV_UI_PORT="${DEV_UI_PORT:-8089}" DEV_GRAFANA_PORT="${DEV_GRAFANA_PORT:-8090}"
else
    PROJECT="garagebooks-dev-$INSTANCE"
    export DEV_BASE_PATH="/garagebooks-dev/$INSTANCE" DEV_ROUTER_SUFFIX="-$INSTANCE" DEV_TAG="dev-$INSTANCE"
    # Above the main stack's routes: /garagebooks-dev/ is a prefix of this path.
    export DEV_UI_PRIORITY=130 DEV_GRAFANA_PRIORITY=140
    # A stable pair of loopback ports per name, clear of the main stack's.
    slot=$(( $(printf '%s' "$INSTANCE" | cksum | cut -d' ' -f1) % 400 ))
    export DEV_UI_PORT=$((18100 + 2 * slot)) DEV_GRAFANA_PORT=$((18101 + 2 * slot))
fi

compose() {
    local files=(-f docker-compose.dev.yml)
    # PUBLIC_HOST set: publish through the reverse proxy instead of on loopback.
    [ -z "${PUBLIC_HOST:-}" ] || files+=(-f docker-compose.dev.traefik.yml)
    # SCHEDULER=worker (dev.env): the scheduled jobs run in the dev-worker container, not in the app. `down`
    # always names the profile, so a worker started earlier is stopped too.
    local profile=""
    { [ "${SCHEDULER:-}" != worker ] && [ "${1:-}" != down ]; } || profile=worker
    COMPOSE_PROFILES="$profile" docker compose -p "$PROJECT" "${files[@]}" --env-file "$ENVF" "$@"
}
dev_psql() { compose exec -T dev-db psql -X -q -v ON_ERROR_STOP=1 -U teslamate -d teslamate "$@"; }

# CLAUDE_LOCAL_SOURCE (dev.env): keep CLAUDE.local.md a plain copy of a file kept
# elsewhere. A copy, not a symlink, so .worktreeinclude carries it into new
# worktrees and it loads there at session start.
sync_local_notes() {
    local src="${CLAUDE_LOCAL_SOURCE:-}"
    [ -n "$src" ] || return 0
    [ -f "$src" ] || { echo "dev: CLAUDE_LOCAL_SOURCE $src not found" >&2; return 0; }
    if [ -L CLAUDE.local.md ] || ! cmp -s "$src" CLAUDE.local.md; then
        rm -f CLAUDE.local.md
        cp "$src" CLAUDE.local.md
        echo "dev: CLAUDE.local.md refreshed from $src"
    fi
}

# The commands that use the invoice folder call this first (taking a stack down or removing it doesn't:
# that must work with the NAS off). A folder that isn't there is a share that didn't mount, not one to
# create. With DEV_INVOICES_SHARE the share itself must be a real mount, and only this stack's folder in
# it is made: an empty mount point on this machine's own disk must not quietly fill up.
require_invoices() {
    if [ -n "$INVOICES_SHARE" ]; then
        ls "$INVOICES_SHARE" >/dev/null 2>&1   # touches an automount, which mounts on first use
        mountpoint -q "$INVOICES_SHARE" || {
            echo "dev: DEV_INVOICES_SHARE $INVOICES_SHARE isn't mounted (is the share up?); nothing was changed" >&2
            exit 1
        }
        [ -d "$DEV_INVOICES_DIR" ] || mkdir "$DEV_INVOICES_DIR"
        echo "dev: invoice folder $DEV_INVOICES_DIR (on the share, for this stack only)"
    fi
    [ -d "$DEV_INVOICES_DIR" ] || { echo "dev: DEV_INVOICES_DIR $DEV_INVOICES_DIR isn't there (not mounted?)" >&2; exit 1; }
}

ensure_env() {
    sync_local_notes
    mkdir -p "$SHOTS" "$INVOICES"
    if [ ! -f "$ENVF" ]; then
        ( umask 077
          printf 'DEV_ADMIN_DB_PASS=%s\nDEV_GRAFANA_PASS=%s\n' \
              "$(openssl rand -hex 24)" "$(openssl rand -hex 24)" > "$ENVF" )
    fi
    # Added later than the passwords, so older .dev/env files get it too.
    # (Renamed from DEV_ONEDRIVE_TOKEN_KEY: keep the old value so saved dev sign-ins still decrypt.)
    grep -q '^DEV_ENCRYPTION_KEY=' "$ENVF" || {
        old=$(sed -n 's/^DEV_ONEDRIVE_TOKEN_KEY=//p' "$ENVF")
        printf 'DEV_ENCRYPTION_KEY=%s\n' "${old:-$(openssl rand -base64 32 | tr '+/' '-_')}" >> "$ENVF"
    }
}

# ---- reading TeslaMate (never writes) ----------------------------------------

source_psql() {
    docker exec -e "SQL=$1" "$SEED_FROM" \
        sh -c 'psql -X -At -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d "$POSTGRES_DB" -c "$SQL"'
}

require_source() {
    docker inspect "$SEED_FROM" >/dev/null 2>&1 || {
        echo "dev: TeslaMate database container '$SEED_FROM' not found (set SEED_FROM in dev.env)" >&2
        exit 1
    }
}

dump_schema() {
    scripts/dump-teslamate-schema.sh "$SEED_FROM"
}

columns_of() {
    source_psql "SELECT string_agg(quote_ident(column_name), ',' ORDER BY ordinal_position)
                 FROM information_schema.columns
                 WHERE table_schema = 'public' AND table_name = '$1'"
}

# Same columns, with everything that reveals a location blanked.
position_select_list() {
    source_psql "SELECT string_agg(CASE column_name
                     WHEN 'latitude'  THEN '0'
                     WHEN 'longitude' THEN '0'
                     WHEN 'elevation' THEN 'NULL'
                     ELSE quote_ident(column_name) END, ',' ORDER BY ordinal_position)
                 FROM information_schema.columns
                 WHERE table_schema = 'public' AND table_name = 'positions'"
}

# ---- loading the test database -------------------------------------------------

copy_data() {
    require_source
    local car_cols charge_cols position_cols position_select
    car_cols="$(columns_of cars)"
    charge_cols="$(columns_of charging_processes)"
    position_cols="$(columns_of positions)"
    position_select="$(position_select_list)"
    echo "dev: copying TeslaMate data from $SEED_FROM (read-only)..."
    # One transaction: if any step fails, EOF without COMMIT rolls it all back.
    # cars is merged, not truncated: test expenses reference it.
    {
        cat <<SQL
BEGIN;
-- TeslaMate's real tables point at addresses, geofences and settings that are not copied (addresses
-- are locations): skip those foreign-key checks for this transaction, in this throwaway database only.
SET LOCAL session_replication_role = replica;
TRUNCATE public.positions, public.charging_processes CASCADE;   -- CASCADE: the real tables (drives, charges) reference them; expenses.* does not
CREATE TEMP TABLE incoming_cars (LIKE public.cars) ON COMMIT DROP;
COPY incoming_cars ($car_cols) FROM STDIN;
SQL
        source_psql "COPY (SELECT $car_cols FROM cars) TO STDOUT"
        cat <<SQL
\\.
INSERT INTO public.cars SELECT * FROM incoming_cars ON CONFLICT (id) DO NOTHING;
COPY public.charging_processes ($charge_cols) FROM STDIN;
SQL
        source_psql "COPY (SELECT $charge_cols FROM charging_processes) TO STDOUT"
        cat <<SQL
\\.
COPY public.positions ($position_cols) FROM STDIN;
SQL
        source_psql "COPY (SELECT DISTINCT ON (car_id, date_trunc('hour', date)) $position_select
                           FROM positions WHERE odometer IS NOT NULL
                           ORDER BY car_id, date_trunc('hour', date), date) TO STDOUT"
        cat <<SQL
\\.
DO \$\$ BEGIN
    IF EXISTS (SELECT 1 FROM public.positions
               WHERE latitude <> 0 OR longitude <> 0 OR elevation IS NOT NULL) THEN
        RAISE EXCEPTION 'location data reached the test database; rolling back';
    END IF;
END \$\$;
COMMIT;
SQL
    } | dev_psql
    dev_psql -At -c "SELECT 'dev: test DB has ' || (SELECT count(*) FROM public.cars) || ' car(s), '
        || (SELECT count(*) FROM public.charging_processes) || ' charges, '
        || (SELECT count(*) FROM public.positions) || ' hourly odometer readings, '
        || (SELECT count(*) FROM garagebooks.expense) || ' test expense(s)'"
}

# Generated rows only (scripts/demo-seed.sql); nothing is read from TeslaMate's data.
demo_data() {
    dev_psql < scripts/demo-seed.sql
    dev_psql -v "tz=$APP_TZ" < scripts/dev-sample-expenses.sql
    # Made-up invoices in the invoice folder, and each car pointed at them, for the import screenshots.
    python3 scripts/dev-sample-invoices.py "$ROOT/$INVOICES" >/dev/null
    # The car is pointed at it below, not through the app, so leave the marker choosing a folder would.
    printf 'Demo invoice folder for garagebooks.\n' > "$ROOT/$INVOICES/.garagebooks"
    dev_psql -c "INSERT INTO garagebooks.car_folder (car_id, folder_id, folder_path, backend)
                 SELECT id, '/Sample invoices', '/Sample invoices', 'local' FROM public.cars
                 ON CONFLICT (car_id) DO NOTHING"
    # The app works out the dashboard's time range from the data at start-up, and started with none.
    compose restart garagebooks-dev >/dev/null
    compose up -d --wait >/dev/null
    dev_psql -At -c "SELECT 'dev: demo DB has ' || (SELECT count(*) FROM public.charging_processes) || ' charges, '
        || (SELECT count(*) FROM public.positions) || ' odometer readings, '
        || (SELECT count(*) FROM garagebooks.expense) || ' expenses'"
}

# TeslaMate's own tables, created by the release this app was tested with: its image migrates the
# empty dev database, as it does in production. Nothing of TeslaMate's is kept in this repository.
migrate_with_teslamate_image() {
    local version db pass
    version="$(.venv/bin/python -c 'from garagebooks import compat; print(compat.TESTED_TESLAMATE)')"
    db="$(compose ps -q dev-db)"
    pass="$(sed -n 's/^DEV_ADMIN_DB_PASS=//p' "$ENVF")"
    docker run --rm --network "container:$db" -e DATABASE_HOST=127.0.0.1 -e DATABASE_USER=teslamate \
        -e "DATABASE_PASS=$pass" -e DATABASE_NAME=teslamate -e ENCRYPTION_KEY=dev-only \
        -e DISABLE_MQTT=true "teslamate/teslamate:$version" /bin/dash -c true
}

# TeslaMate's own tables, as TeslaMate would have created them. Our schema is not
# loaded here: the app creates it when it starts, exactly as it does in production.
# Sets FIRST_RUN for seed_data.
prepare_database() {
    compose up -d --wait dev-db
    FIRST_RUN=no
    if [ "$(dev_psql -At -c "SELECT to_regclass('public.cars') IS NULL")" = t ]; then
        FIRST_RUN=yes
        if [ "$DEMO" = 1 ]; then
            # The live TeslaMate's own tables, structure only, so the demo can't fall behind it.
            require_source
            dump_schema | dev_psql
        else
            migrate_with_teslamate_image
        fi
    fi
}

seed_data() {
    [ "$FIRST_RUN" = yes ] || return 0
    if [ "$DEMO" = 1 ]; then demo_data; else copy_data; fi
    seed_settings
}

# What you would type on the app's Settings page, for this stack's own addresses.
seed_settings() {
    local app graf
    if [ -n "${PUBLIC_HOST:-}" ]; then
        app="https://$PUBLIC_HOST$DEV_BASE_PATH/"; graf="https://$PUBLIC_HOST$DEV_BASE_PATH/grafana/"
    else
        app="http://localhost:$DEV_UI_PORT$DEV_BASE_PATH/"
        graf="http://localhost:$DEV_GRAFANA_PORT$DEV_BASE_PATH/grafana/"
    fi
    dev_psql -q -v "app=$app" -v "graf=$graf" <<'SQL'
UPDATE garagebooks.setting SET app_url = :'app', grafana_url = :'graf' WHERE id = 1;
SQL
}

start() {
    local image="${1:-}"
    ensure_env
    require_invoices
    claims_keys
    prepare_database
    if [ -n "$image" ]; then
        export GARAGEBOOKS_IMAGE="$image"
        compose pull garagebooks-dev
        compose up -d --no-build --wait
    else
        compose up -d --build --wait
    fi
    seed_data
    urls
}

urls() {
    local base
    if [ -n "${PUBLIC_HOST:-}" ]; then base="https://$PUBLIC_HOST"; else base="http://localhost:$DEV_UI_PORT"; fi
    echo "dev: UI      $base$DEV_BASE_PATH/"
    [ -n "${PUBLIC_HOST:-}" ] || base="http://localhost:$DEV_GRAFANA_PORT"
    echo "dev: Grafana $base$DEV_BASE_PATH/grafana/"
}

info() {
    cat <<INFO
project=$PROJECT
instance=${INSTANCE:-main}
base_path=$DEV_BASE_PATH
ui_port=$DEV_UI_PORT
grafana_port=$DEV_GRAFANA_PORT
image=${GARAGEBOOKS_IMAGE:-garagebooks:$DEV_TAG}
invoices=$DEV_INVOICES_DIR
router_suffix=${DEV_ROUTER_SUFFIX:-none}
ui_priority=$DEV_UI_PRIORITY
grafana_priority=$DEV_GRAFANA_PRIORITY
INFO
}

setup() {
    sync_local_notes
    [ -x .venv/bin/python ] || python3 -m venv .venv
    # Install on the first run, and again whenever a requirements file is newer than the last install: merging
    # main can add a dependency, and a venv from before it fails with ModuleNotFoundError.
    local stamp=.venv/.requirements-installed
    if [ ! -f "$stamp" ] || [ requirements.txt -nt "$stamp" ] || [ requirements-dev.txt -nt "$stamp" ]; then
        .venv/bin/pip install -q -r requirements-dev.txt
        touch "$stamp"
    fi
    echo "dev: .venv ready"
    [ -f dev.env ] || echo "dev: no dev.env, so this stack is on localhost with defaults (see dev.env.example)"
    [ -e CLAUDE.local.md ] || echo "dev: no CLAUDE.local.md here (optional, local notes for Claude)"
    urls
}

test_browser() {
    local require_onedrive="${1:-0}"
    ensure_env
    docker build -q -t garagebooks:browser-tests tests/browser >/dev/null
    # Straight to the containers on the dev network, past the proxy's login.
    docker run --rm --network "${PROJECT}_dev" --user "$(id -u):$(id -g)" \
        -e HOME=/tmp -e OUT=/out -e "BASE_PATH=$DEV_BASE_PATH" -e "REQUIRE_ONEDRIVE=$require_onedrive" \
        -v "$ROOT/tests/browser:/tests:ro" -v "$ROOT/$SHOTS:/out" \
        garagebooks:browser-tests python3 /tests/run.py
}

